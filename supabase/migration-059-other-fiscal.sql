-- ============================================================
-- Редът „Финансов отчет РЗОК" се преименува на „Други фискализирани
-- документи 20%" и получава близнак за 9% — същата логика като при
-- всички останали двойки в справката.
--
-- СПО 20% = (Общо20 − Сторно20) − Фактури20 − ДругиФиск20 + КИ20
-- СПО 9%  = (Общо9  − Сторно9)  − Фактури9  − ДругиФиск9  + КИ9
--
-- ЗАЩО НЕ ПРЕИМЕНУВАМ КОЛОНАТА `rzok`: миграциите тук са само additive.
-- Преименуването щеше да остави прозорец (миграцията минава преди
-- Cloudflare да е качил новия билд), в който живият код пише в колона,
-- която вече не съществува — и записът гърми. Затова се добавят нови
-- колони, старата стойност се пренася, а `rzok` остава НЕИЗПОЛЗВАНА.
-- Може да се махне отделно, след като новите се потвърдят на живо.
--
-- Идемпотентно.
-- ============================================================

alter table crm_cash_firm_monthly
  add column if not exists other_fiscal_20 numeric not null default 0,
  add column if not exists other_fiscal_9  numeric not null default 0;

-- Пренасяне на досегашните стойности от РЗОК в полето за 20%.
-- Условието пази от презаписване при повторно пускане: щом стойността е
-- пренесена, other_fiscal_20 вече не е нула.
update crm_cash_firm_monthly
   set other_fiscal_20 = rzok
 where rzok <> 0 and other_fiscal_20 = 0;

